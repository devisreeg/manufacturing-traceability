import argparse
import csv
import hashlib
import json
from contextlib import closing
from datetime import datetime, timezone
from pathlib import Path

from app.database import PROJECT_ROOT, get_connection
from app.generator import SEED


TABLES = [
    "products",
    "suppliers",
    "bom",
    "material_lots",
    "machines",
    "production_orders",
    "order_material_consumption",
    "process_steps",
    "inspection_plans",
    "inspection_results",
    "defects",
    "corrective_actions",
    "event_history",
]


def sha256_file(path):
    """Calculate a file's SHA-256 checksum."""
    digest = hashlib.sha256()

    with path.open("rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)

    return digest.hexdigest()


def export_csv(connection, output_dir):
    """Export every database table to a separate CSV file."""
    csv_dir = output_dir / "csv"
    csv_dir.mkdir(parents=True, exist_ok=True)

    record_counts = {}

    for table in TABLES:
        cursor = connection.execute(f'SELECT * FROM "{table}"')
        columns = [description[0] for description in cursor.description]
        rows = cursor.fetchall()

        output_path = csv_dir / f"{table}.csv"

        with output_path.open(
            "w", newline="", encoding="utf-8-sig"
        ) as file:
            writer = csv.writer(file)
            writer.writerow(columns)
            writer.writerows(rows)

        record_counts[table] = len(rows)

    return record_counts


def export_json(connection, output_dir, scale, record_counts):
    """Export all database tables and metadata to JSON."""
    data = {}

    for table in TABLES:
        cursor = connection.execute(f'SELECT * FROM "{table}"')
        columns = [description[0] for description in cursor.description]

        data[table] = [
            dict(zip(columns, row))
            for row in cursor.fetchall()
        ]

    document = {
        "metadata": {
            "project": "Manufacturing Defect Traceability and CAPA System",
            "scale": scale,
            "seed": SEED,
            "exported_at_utc": datetime.now(timezone.utc).isoformat(),
            "record_counts": record_counts,
        },
        "tables": data,
    }

    output_path = output_dir / "manufacturing_export.json"

    with output_path.open("w", encoding="utf-8") as file:
        json.dump(document, file, indent=2, ensure_ascii=False)

    return output_path


def export_sql(connection, output_dir):
    """Export the SQLite schema and all database records as SQL."""
    output_path = output_dir / "manufacturing_export.sql"

    with output_path.open("w", encoding="utf-8", newline="\n") as file:
        file.write("-- Manufacturing Traceability and CAPA database export\n")
        file.write("-- Generated by app.exports\n\n")

        for statement in connection.iterdump():
            file.write(f"{statement}\n")

    return output_path


def create_manifest(output_dir, scale, record_counts, exported_files):
    """Write metadata and SHA-256 checksums for exported artifacts."""
    manifest = {
        "project": "Manufacturing Defect Traceability and CAPA System",
        "scale": scale,
        "seed": SEED,
        "exported_at_utc": datetime.now(timezone.utc).isoformat(),
        "record_counts": record_counts,
        "files": {
            str(path.relative_to(output_dir)): {
                "size_bytes": path.stat().st_size,
                "sha256": sha256_file(path),
            }
            for path in exported_files
        },
    }

    manifest_path = output_dir / "manifest.json"

    with manifest_path.open("w", encoding="utf-8") as file:
        json.dump(manifest, file, indent=2)

    return manifest_path


def export_all(scale="unknown", output_dir=None):
    """Export the current database to CSV, JSON, SQL, and a manifest."""
    if output_dir is None:
        output_dir = PROJECT_ROOT / "exports"
    else:
        output_dir = Path(output_dir).resolve()

    output_dir.mkdir(parents=True, exist_ok=True)

    with closing(get_connection()) as connection:
        integrity = connection.execute(
            "PRAGMA integrity_check"
        ).fetchone()[0]

        if integrity != "ok":
            raise RuntimeError(
                f"Database integrity check failed: {integrity}"
            )

        record_counts = export_csv(connection, output_dir)
        json_path = export_json(
            connection, output_dir, scale, record_counts
        )
        sql_path = export_sql(connection, output_dir)

    exported_files = [
        *sorted((output_dir / "csv").glob("*.csv")),
        json_path,
        sql_path,
    ]

    manifest_path = create_manifest(
        output_dir, scale, record_counts, exported_files
    )

    print("Export completed successfully.")
    print(f"Output directory: {output_dir}")
    print(f"Tables exported: {len(record_counts)}")
    print(f"Total records: {sum(record_counts.values())}")
    print(f"JSON: {json_path}")
    print(f"SQL: {sql_path}")
    print(f"Manifest: {manifest_path}")

    return manifest_path


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Export manufacturing database to CSV, JSON, and SQL."
    )
    parser.add_argument(
        "--scale",
        choices=["small", "full"],
        default="small",
        help="Dataset scale currently stored in the database.",
    )
    parser.add_argument(
        "--output",
        default=None,
        help="Optional export directory. Defaults to project_root/exports.",
    )

    args = parser.parse_args()
    export_all(scale=args.scale, output_dir=args.output)
